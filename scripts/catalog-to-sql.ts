/**
 * Turn catalog/catalog.json into SQL that can be pasted into the Supabase SQL
 * editor (no service-role key needed). Validates the file first.
 *
 *   npm run catalog:sql            # writes supabase/seed/catalog.sql
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { catalogFileSchema } from '../src/data/catalogSchema.ts';

const file = resolve(process.argv[2] ?? 'catalog/catalog.json');
const out = resolve(process.argv[3] ?? 'supabase/seed/catalog.sql');
const parsed = catalogFileSchema.safeParse(JSON.parse(readFileSync(file, 'utf8')));
if (!parsed.success) {
  for (const issue of parsed.error.issues) console.error(`  • ${issue.path.join('.')}: ${issue.message}`);
  process.exit(1);
}
const c = parsed.data;

const q = (v: string | null | undefined) => (v === null || v === undefined ? 'null' : `'${v.replace(/'/g, "''")}'`);
const arr = (v: string[]) => (v.length ? `array[${v.map(q).join(', ')}]::text[]` : `'{}'::text[]`);
const json = (v: object) => `${q(JSON.stringify(v))}::jsonb`;

const lines: string[] = [
  '-- Generated by scripts/catalog-to-sql.ts from catalog/catalog.json. Safe to re-run (upserts).',
  'begin;',
];

// Parents before children (self-referencing categories).
const ordered: typeof c.categories = [];
const pending = [...c.categories];
while (pending.length) {
  const index = pending.findIndex((cat) => !cat.parentId || ordered.some((o) => o.id === cat.parentId));
  ordered.push(...pending.splice(index === -1 ? 0 : index, 1));
}
for (const cat of ordered) {
  lines.push(
    `insert into public.categories (id, parent_id, name_ar, name_en, image, sort_order) values (${q(cat.id)}, ${q(cat.parentId)}, ${q(cat.nameAr)}, ${q(cat.nameEn)}, ${q(cat.image)}, ${cat.sortOrder})` +
      ` on conflict (id) do update set parent_id = excluded.parent_id, name_ar = excluded.name_ar, name_en = excluded.name_en, image = excluded.image, sort_order = excluded.sort_order;`,
  );
}
for (const p of c.products) {
  lines.push(
    `insert into public.products (id, category_id, name_ar, name_en, description_ar, description_en, sold_as, images, tags, is_active) values (${q(p.id)}, ${q(p.categoryId)}, ${q(p.nameAr)}, ${q(p.nameEn)}, ${q(p.descriptionAr)}, ${q(p.descriptionEn)}, ${q(p.soldAs)}, ${arr(p.images)}, ${arr(p.tags)}, ${p.isActive})` +
      ` on conflict (id) do update set category_id = excluded.category_id, name_ar = excluded.name_ar, name_en = excluded.name_en, description_ar = excluded.description_ar, description_en = excluded.description_en, sold_as = excluded.sold_as, images = excluded.images, tags = excluded.tags, is_active = excluded.is_active;`,
  );
  p.variants.forEach((v, index) => {
    lines.push(
      `insert into public.product_variants (sku, product_id, barcode, shade_name_ar, shade_name_en, shade_hex, size, images, prices, compare_at, available, low_stock_threshold, sort_order) values (${q(v.sku)}, ${q(p.id)}, ${q(v.barcode)}, ${q(v.shadeNameAr)}, ${q(v.shadeNameEn)}, ${q(v.shadeHex)}, ${q(v.size)}, ${arr(v.images)}, ${json(v.prices)}, ${json(v.compareAt)}, ${v.available}, ${v.lowStockThreshold}, ${index})` +
        // Stock is only set on first insert so re-running never overwrites live stock.
        ` on conflict (sku) do update set product_id = excluded.product_id, barcode = excluded.barcode, shade_name_ar = excluded.shade_name_ar, shade_name_en = excluded.shade_name_en, shade_hex = excluded.shade_hex, size = excluded.size, images = excluded.images, prices = excluded.prices, compare_at = excluded.compare_at, low_stock_threshold = excluded.low_stock_threshold, sort_order = excluded.sort_order;`,
    );
  });
}
c.heroSlides.forEach((s, index) => {
  lines.push(
    `insert into public.hero_slides (id, eyebrow_ar, eyebrow_en, title_ar, title_en, body_ar, body_en, image, product_id, deep_link, sort_order, is_active) values (${q(s.id)}, ${q(s.eyebrowAr)}, ${q(s.eyebrowEn)}, ${q(s.titleAr)}, ${q(s.titleEn)}, ${q(s.bodyAr)}, ${q(s.bodyEn)}, ${q(s.image)}, ${q(s.productId)}, ${q(s.deepLink)}, ${index}, true)` +
      ` on conflict (id) do update set eyebrow_ar = excluded.eyebrow_ar, eyebrow_en = excluded.eyebrow_en, title_ar = excluded.title_ar, title_en = excluded.title_en, body_ar = excluded.body_ar, body_en = excluded.body_en, image = excluded.image, product_id = excluded.product_id, deep_link = excluded.deep_link, sort_order = excluded.sort_order, is_active = true;`,
  );
});
for (const b of c.banners) {
  lines.push(
    `insert into public.banners (id, placement, title_ar, title_en, image, deep_link, sort_order, is_active) values (${q(b.id)}, ${q(b.placement)}, ${q(b.titleAr)}, ${q(b.titleEn)}, ${q(b.image)}, ${q(b.deepLink)}, ${b.sortOrder}, true)` +
      ` on conflict (id) do update set placement = excluded.placement, title_ar = excluded.title_ar, title_en = excluded.title_en, image = excluded.image, deep_link = excluded.deep_link, sort_order = excluded.sort_order, is_active = true;`,
  );
}
lines.push('commit;', '');
writeFileSync(out, lines.join('\n'));
const variants = c.products.reduce((n, p) => n + p.variants.length, 0);
console.log(`✔ wrote ${out}: ${c.categories.length} categories, ${c.products.length} products, ${variants} variants`);
